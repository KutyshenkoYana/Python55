# (додаткове на кристалики)Використовуючи лямбдафункцію, напишіть вираз, який сортує список кортежів
# за другим елементом кожного кортежу (наприклад,
# [(1,3), (3, 2), (2, 1)]).

lst = [(1, 3), (3, 2), (2, 1)]

sorted_list = sorted(lst, key=lambda x: x[1])

print(sorted_list)

